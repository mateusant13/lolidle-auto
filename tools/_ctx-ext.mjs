const list = await (await fetch('http://127.0.0.1:9337/json/list')).json();
const pg = list.find(t => t.type === 'page' && /lolidle/.test(t.url));
if (!pg) { console.log('sem aba'); process.exit(0); }
const ws = new WebSocket(pg.webSocketDebuggerUrl);
let id = 0; const pend = new Map(); const ctxs = [];
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id !== undefined && pend.has(m.id)) { pend.get(m.id)(m); pend.delete(m.id); } else if (m.method === 'Runtime.executionContextCreated') ctxs.push(m.params.context); });
await new Promise(r => ws.addEventListener('open', r, { once: true }));
const send = (m, p) => new Promise(r => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify({ id: i, method: m, params: p || {} })); setTimeout(() => r({ __t: true }), 12000); });
await send('Runtime.enable');
await send('Page.enable');
await send('Page.reload', { ignoreCache: true });
await new Promise(r => setTimeout(r, 9000));
console.log('contextos apos reload (' + ctxs.length + '): ' + ctxs.map(c => (c.origin || '?').slice(0, 40)).join(' | ').slice(0, 300));
const ext = ctxs.find(c => /^chrome-extension:/.test(c.origin || ''));
const alvo = ext || ctxs.find(c => /lolidle/.test(c.origin || ''));
console.log('a usar: ' + (alvo ? alvo.origin + ' id=' + alvo.id : 'nenhum'));
if (!alvo) process.exit(0);
const r = await send('Runtime.evaluate', { contextId: alvo.id, returnByValue: true, expression: "JSON.stringify({ temAuto: !!window.__lolidleAuto, temGui: !!document.querySelector('#lolidle-ap-style'), vida: (document.querySelector('#hud-vida-txt')||{}).textContent||null })" });
console.log('SONDA: ' + (r.__t ? 'sem resposta' : String(r.result?.result?.value)));
ws.close(); process.exit(0);