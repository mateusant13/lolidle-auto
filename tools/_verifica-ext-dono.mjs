const list = await (await fetch('http://127.0.0.1:9224/json/list')).json();
const jogos = list.filter(t => t.type === 'page' && /lolidle/.test(t.url));
const ws = new WebSocket('ws://127.0.0.1:9224/cdp');
let id = 0; const pend = new Map();
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id !== undefined && pend.has(m.id)) { pend.get(m.id)(m); pend.delete(m.id); } });
await new Promise(r => ws.addEventListener('open', r, { once: true }));
const send = (m, p, sid) => new Promise(r => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify(sid ? { id: i, method: m, params: p||{}, sessionId: sid } : { id: i, method: m, params: p||{} })); setTimeout(() => r({ __t: true }), 15000); });
console.log('abas do jogo: ' + jogos.length);
// fecho as MINHAS (se houver mais de uma, a tua e a primeira) - e abro UMA nova pelo relay
for (const t of jogos.slice(1)) await send('Target.closeTarget', { targetId: t.targetId });
await new Promise(r => setTimeout(r, 2000));
const nt = await send('Target.createTarget', { url: 'https://lolidle.com/jogar' });
const s = (await send('Target.attachToTarget', { targetId: nt.result.targetId, flatten: true })).result?.sessionId;
console.log('aba nova pelo relay: ' + (s ? 'ok' : 'FALHOU'));
if (!s) process.exit(0);
await send('Runtime.enable', {}, s);
await new Promise(r => setTimeout(r, 15000));
const r = await send('Runtime.evaluate', { expression: "JSON.stringify({ login: /Bem-vindo de volta|Senha/i.test(document.body ? document.body.innerText : ''), local: (document.querySelector('#local-nome')||{}).textContent||null, vida: (document.querySelector('#hud-vida-txt')||{}).textContent||null, auto: typeof window.__lolidleAuto, painel: !!document.querySelector('#lolidle-ap-style') })", returnByValue: true }, s);
console.log('ESTADO: ' + (r.__t ? 'sem resposta' : String(r.result?.result?.value)));
ws.close(); process.exit(0);