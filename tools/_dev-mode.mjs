const list = await (await fetch('http://127.0.0.1:9224/json/list')).json();
const antigas = list.filter(t => t.type === 'page' && /^(chrome:\/\/extensions|lolidle)/.test(t.url));
const ws = new WebSocket('ws://127.0.0.1:9224/cdp');
let id = 0; const pend = new Map();
ws.addEventListener('message', e => { const m = JSON.parse(e.data); if (m.id !== undefined && pend.has(m.id)) { pend.get(m.id)(m); pend.delete(m.id); } });
await new Promise(r => ws.addEventListener('open', r, { once: true }));
const send = (m, p, sid) => new Promise(r => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify(sid ? { id: i, method: m, params: p||{}, sessionId: sid } : { id: i, method: m, params: p||{} })); setTimeout(() => r({ __t: true }), 15000); });
console.log('abas a fechar (minhas): ' + antigas.length);
for (const t of antigas) await send('Target.closeTarget', { targetId: t.targetId });
await new Promise(r => setTimeout(r, 2000));
const nt = await send('Target.createTarget', { url: 'chrome://extensions/' });
const s = (await send('Target.attachToTarget', { targetId: nt.result.targetId, flatten: true })).result?.sessionId;
console.log('aba chrome://extensions: ' + (s ? 'ok' : 'FALHOU'));
if (!s) process.exit(0);
await send('Accessibility.enable', {}, s); await send('DOM.enable', {}, s);
await new Promise(r => setTimeout(r, 6000));
const ax = await send('Accessibility.getFullAXTree', {}, s);
const nos = ax.result ? ax.result.nodes : [];
const nomes = nos.map(n => (n.name && n.name.value) || '').filter(Boolean);
console.log('textos (' + nomes.length + '): ' + JSON.stringify(nomes.slice(0, 20)).slice(0, 500));
const dev = nos.find(n => /programador|developer mode/i.test((n.name && n.name.value) || ''));
console.log('toggle dev mode: ' + (dev ? JSON.stringify(dev.name.value) + ' role=' + dev.role.value + ' backend=' + dev.backendDOMNodeId : 'NAO ACHEI'));
ws.close(); process.exit(0);